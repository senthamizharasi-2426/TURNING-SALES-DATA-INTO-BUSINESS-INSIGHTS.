-- 8. Staff Performance Analysis 
 -- Analyze total revenue generated by each staff member based on their handled orders.
 select distinct o.Staff_id,sum(oi.Total_price) as Total_revenue from store_fusion.order_items as oi
 join store_fusion.orders as o
