-- 4.Total Sales by Store
-- Write a query to group sales(total_price) by each store_id.
select o.Store_id as Store_id,sum(oi.Total_price) as Total_price from store_fusion.orders as o
join store_fusion.order_items as oi 
on o.order_id=oi.order_id
group by Store_id;
-- 5.Top Selling Products
-- Use ORDER BY and LIMIT to get the top 5 most sold products by quantity.
select sum(oi.Quantity) as Total_Quantity,p.Product_id as Product_id from store_fusion.order_items as oi
join store_fusion.products as p
on p.Product_id=oi.Product_id
group by Product_id
order by sum(oi.Quantity) desc limit 5;


