-- 9. Stock Alert Query 
-- Write a query to list products where stock quantity < 10 in any store.
select p.Product_name as product_name,stor.Store_name as Store_name,sum(st.Quantity) as Quantity from store_fusion.stocks as st
join store_fusion.stores as stor
on stor.Store_id=st.Store_id
join store_fusion.products as p
on p.Product_id=st.Product_id
group by product_name,Store_name
having sum(st.Quantity)<10; 


